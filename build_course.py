"""Validate the curriculum and regenerate dist/course-data.js."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def load(name):
    return json.loads((ROOT / "curriculum" / name).read_text(encoding="utf-8"))


def validate(weeks, lessons, audio):
    if [week["number"] for week in weeks] != list(range(1, 37)):
        raise ValueError("weeks.json must contain weeks 1–36 in order")

    by_id = {lesson["id"]: lesson for lesson in lessons}
    if len(by_id) != len(lessons):
        raise ValueError("Duplicate lesson ID")
    for week in weeks:
        for track in ("lessons", "academic", "general"):
            for code in week.get(track, []):
                if code not in by_id:
                    raise ValueError(f"Week {week['number']} references missing lesson {code}")

    for lesson in lessons:
        code = lesson["id"]
        clip = lesson.get("audio")
        if clip and clip not in audio:
            raise ValueError(f"{code} is missing the transcript for {clip}")
        for group in lesson.get("groups", []):
            for question in group["questions"]:
                answers = question.get("answers", [])
                if not answers and not question.get("model"):
                    raise ValueError(f"{code}: question has no answer or model")
                if any(not answer.strip() for answer in answers):
                    raise ValueError(f"{code}: blank accepted answer")
                if question.get("options"):
                    labels = {
                        (option.split(". ", 1)[0]).casefold()
                        for option in question["options"]
                    }
                    if answers[0].casefold() not in labels:
                        raise ValueError(f"{code}: answer {answers[0]} is missing from its choices")
    for code, turns in audio.items():
        path = ROOT / "dist" / "audio" / f"{code}.mp3"
        if not turns or not all(turn["text"].strip() for turn in turns):
            raise ValueError(f"{code}: missing transcript lines")
        if not path.is_file() or not path.stat().st_size:
            raise ValueError(f"{code}: missing {path.name}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that the generated file is up to date")
    args = parser.parse_args()
    weeks, lessons, audio = (load(name) for name in ("weeks.json", "lessons.json", "audio.json"))
    validate(weeks, lessons, audio)
    version = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))["version"]
    data = json.dumps({"version": version, "weeks": weeks, "lessons": lessons, "audio": audio}, ensure_ascii=False, separators=(",", ":"))
    output = ROOT / "dist" / "course-data.js"
    generated = f"// Generated by build_course.py\nwindow.COURSE = {data};\n"
    if args.check:
        if not output.is_file() or output.read_text(encoding="utf-8") != generated:
            parser.exit(1, "Run python3 build_course.py to update dist/course-data.js.\n")
    else:
        output.write_text(generated, encoding="utf-8")
    print(f"{len(weeks)} weeks, {len(lessons)} lessons, {len(audio)} MP3 files")


if __name__ == "__main__":
    main()
